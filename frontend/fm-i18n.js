// ---- 다국어 UI 문자열 테이블 ----
// settings.uiLang 기준으로 문자열을 조회한다. manifest.json 로드 순서상
// fm-core.js 바로 다음, fm-filter.js보다 앞에 와야 다른 fm-*.js 파일들이
// t()를 바로 쓸 수 있다.

function t(key, vars) {
  const lang = (typeof settings !== 'undefined' && settings && settings.uiLang) || 'ko';
  let str = (I18N[lang] && I18N[lang][key]) || I18N.ko[key] || key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => { str = str.replace(`{${k}}`, v); });
  }
  return str;
}

